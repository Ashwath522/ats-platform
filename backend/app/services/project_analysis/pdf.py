"""Render an analysis result as a PDF with reportlab (already a dependency)."""
from __future__ import annotations

import io
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

STATUS = {"verified": "Verified", "partially_verified": "Partly verified", "unverified": "Unverified", "contradicted": "Contradicted", "not_checked": "Not checked"}


def _p(text, style):
    return Paragraph(escape(str(text or "")), style)


def render(result: dict, title: str, student: str = "") -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=16 * mm, rightMargin=16 * mm, topMargin=16 * mm, bottomMargin=16 * mm,
                            title=f"CoreLink project report — {title}")
    ss = getSampleStyleSheet()
    body = ParagraphStyle("b", parent=ss["BodyText"], fontSize=9.5, leading=13)
    small = ParagraphStyle("s", parent=body, fontSize=8, leading=10, textColor=colors.HexColor("#555555"))
    h1, h2 = ss["Title"], ParagraphStyle("h2", parent=ss["Heading2"], fontSize=12.5, spaceBefore=10, spaceAfter=4)
    out = [_p(f"Project analysis: {title}", h1)]
    if student:
        out.append(_p(student, small))
    sc = result.get("scores") or {}
    out.append(_p(f"Overall: {sc.get('overall') if sc.get('overall') is not None else 'not enough evidence'}"
                  f"{'/100' if sc.get('overall') is not None else ''} · evidence coverage {sc.get('coverage', 0)}%", body))
    rows = [["Dimension", "Score", "Why"]]
    for d in (sc.get("dimensions") or {}).values():
        rows.append([_p(d["label"], body), "—" if d["score"] is None else f"{d['score']}/10", _p(d["reason"], small)])
    if len(rows) > 1:
        t = Table(rows, colWidths=[45 * mm, 18 * mm, 112 * mm], repeatRows=1)
        t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eef2ff")), ("GRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#cccccc")),
                               ("VALIGN", (0, 0), (-1, -1), "TOP"), ("FONTSIZE", (0, 0), (-1, -1), 8.5)]))
        out += [Spacer(1, 6), t]
    claims = {c["id"]: c for c in result.get("claims", [])}
    ev = result.get("evidence", [])
    for sec in (result.get("report") or {}).get("sections", []):
        out.append(_p(sec["title"], h2))
        if sec.get("text"):
            out.append(_p(sec["text"], body))
        for it in sec.get("items") or []:
            out.append(_p(f"• {it['text']}" + (f"  [{it['evidence_id']}]" if it.get("evidence_id") else ""), body))
        for cid in sec.get("claims") or []:
            c = claims.get(cid)
            if c:
                out.append(_p(f"• [{STATUS.get(c['status'], c['status'])}] {c['text']} — {c.get('reasoning', '')}"
                              + (f" (evidence: {', '.join(c.get('evidence_ids', []))})" if c.get("evidence_ids") else ""), body))
        if sec["id"] in {"verified", "unverified"} and not sec.get("claims"):
            out.append(_p("None.", body))
        data = sec.get("data") or {}
        if sec["id"] == "components":
            for k, v in data.items():
                if v:
                    if isinstance(v, list) and v and isinstance(v[0], dict):
                        v = ", ".join(" ".join(str(x) for x in r.values() if x) for r in v[:40])
                    elif isinstance(v, dict):
                        v = ", ".join(f"{a}: {b}" for a, b in v.items())
                    elif isinstance(v, list):
                        v = ", ".join(str(x) for x in v[:40])
                    out.append(_p(f"{k.replace('_', ' ').title()}: {v}", body))
        if sec["id"] == "architecture" and data.get("pin_map"):
            rows = [["Pin", "Code", "Circuit", "Status"]] + [[r["pin"], r.get("code") or "—", r.get("circuit") or "—", r.get("status")] for r in data["pin_map"][:40]]
            t = Table(rows, colWidths=[20 * mm, 70 * mm, 40 * mm, 30 * mm], repeatRows=1)
            t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#cccccc")), ("FONTSIZE", (0, 0), (-1, -1), 8)]))
            out.append(t)
        if sec["id"] == "video" and sec.get("data"):
            for s in sec["data"].get("segments", [])[:20]:
                out.append(_p(f"{s.get('start')}–{s.get('end')}: {', '.join(s.get('visible', [])[:5])}; "
                              f"inputs {', '.join(s.get('inputs', [])) or '—'} → outputs {', '.join(s.get('outputs', [])) or '—'}", small))
        if sec.get("evidence"):
            for e in ev[:200]:
                out.append(_p(f"{e['id']} · {e['source_type']}:{e['source_ref']} · {e['method']}, {e['confidence']} confidence — {e['fact']}", small))
    out += [Spacer(1, 8), _p("Generated by CoreLink. 'Verified' means the uploaded evidence agrees with a claim; it is not a lab test. "
                             "Structural safety is never certified. A CoreLink reviewer makes the final verification decision.", small)]
    doc.build(out)
    return buf.getvalue()
