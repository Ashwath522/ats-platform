export function Privacy() {
  return (
    <Shell title="Privacy Policy">
      <p>CoreLink is a student project that helps core engineering students find jobs and practise interviews, and helps approved recruiters find candidates. This page explains what we collect and why.</p>
      <h2>What we collect</h2>
      <ul>
        <li><strong>Account details:</strong> your email address and a hashed password. If you use <em>Sign in with Google or LinkedIn</em>, we receive only your name, email address and email-verified status. We do not use your photo or access anything else from either service.</li>
        <li><strong>LinkedIn imports:</strong> a LinkedIn PDF is read once to pre-fill your form and is not stored. A pasted LinkedIn URL is stored only as a link; we never fetch profile pages.</li>
        <li><strong>Profile information you enter:</strong> education, branch, skills, projects, resume and links you choose to add.</li>
        <li><strong>Activity on CoreLink:</strong> jobs you save or apply to, interview practice answers and their scores, and messages from recruiters.</li>
        <li><strong>Interview practice:</strong> when you allow it, your camera and microphone are used live in your browser for the AI interview. Answers are turned into text for feedback; we do not store video. Practice sessions never save any camera image — integrity alerts are shown only to you.</li>
        <li><strong>AI interviews for a job (proctoring):</strong> integrity checks (face in view, other people, looking away for a long time, phones/books/second screens, a covered camera, leaving the tab or full screen, pasting into answers) run on your device; we do not record or upload video. We store a log of the alerts and a small number of still snapshots: one at the start so the reviewer can confirm it is you, and one only when a possible rule break is detected (at most 30 per interview, each labelled with the time and reason). Snapshots and the alert log can be seen only by the hiring company for that job and CoreLink admins, are never used to make an automatic decision, and are deleted after 90 days — or sooner if you request deletion of your interview data.</li>
      </ul>
      <h2>How we use it</h2>
      <ul>
        <li>To run your account and show you matching opportunities and resources.</li>
        <li>To share your profile with approved recruiters when you apply to their jobs (you control what your profile shows in Settings → Privacy).</li>
        <li>To send account emails such as password resets and interview invitations.</li>
      </ul>
      <p>We do not sell your data or use it for advertising.</p>
      <h2>Jobs from other websites</h2>
      <p>Some listings come from official company career sites and job APIs. When you click “Apply on company site” you leave CoreLink, and that site’s own privacy policy applies.</p>
      <h2>Where data is stored</h2>
      <p>Data is stored with our hosting providers (Render for the server, Supabase/PostgreSQL for the database, Vercel for the website). AI feedback is generated by third-party AI services; only the text needed for the feedback is sent. Proctoring snapshots are kept in our database (never sent to AI services) and deleted automatically after 90 days.</p>
      <h2>Your choices</h2>
      <ul>
        <li>Edit your profile and privacy settings at any time.</li>
        <li>Download your data or delete your account from Settings.</li>
        <li>Remove CoreLink’s access to your Google account at <a href="https://myaccount.google.com/permissions" target="_blank" rel="noreferrer">myaccount.google.com/permissions</a>.</li>
        <li>Revoke LinkedIn access at <a href="https://www.linkedin.com/psettings/permitted-services" target="_blank" rel="noreferrer">linkedin.com/psettings/permitted-services</a>.</li>
      </ul>
    </Shell>
  )
}

